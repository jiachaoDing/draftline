import { spawnSync } from "node:child_process";
import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import "./prepare-codex-patch.mjs";
const result = spawnSync(
  process.env.CARGO || "cargo",
  [
    "build",
    "--locked",
    "--manifest-path",
    "third_party/codex/apply-patch/Cargo.toml",
    "--target",
    "wasm32-unknown-unknown",
    "--release",
  ],
  { stdio: "inherit" },
);
if (result.status !== 0) process.exit(result.status || 1);
const bytes = await readFile(
  "third_party/codex/apply-patch/target/wasm32-unknown-unknown/release/draftline_codex_patch.wasm",
);
await writeFile(
  "src/lib/codex-patch-wasm.ts",
  `// Generated by npm run build:patch. OpenAI Codex Apache-2.0.\nexport const codexPatchWasm = "${bytes.toString("base64")}";\n`,
  "utf8",
);
const root = "third_party/codex/apply-patch";
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const rustc =
  process.env.RUSTC ||
  (process.env.CARGO
    ? process.env.CARGO.replace(/cargo(\.exe)?$/, "rustc$1")
    : "rustc");
const compiler = spawnSync(rustc, ["--version"], { encoding: "utf8" });
if (compiler.status !== 0)
  throw new Error("Could not record the Rust compiler version.");
const sources = {};
for (const directory of ["src", "upstream"]) {
  for (const name of await readdir(`${root}/${directory}`)) {
    const file = `${root}/${directory}/${name}`;
    sources[file] = hash(await readFile(file));
  }
}
await writeFile(
  `${root}/build.json`,
  JSON.stringify(
    {
      upstreamCommit: "c22a06c18070c3e33bd2648c7210a00a2a9f6f80",
      compiler: compiler.stdout.trim(),
      target: "wasm32-unknown-unknown",
      wasmSha256: hash(bytes),
      sources,
    },
    null,
    2,
  ) + "\n",
  "utf8",
);
